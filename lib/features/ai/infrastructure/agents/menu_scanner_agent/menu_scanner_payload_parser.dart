import 'package:lens_wise/features/menu_scanner/domain/models/menu_scanner_record.dart';

/// Data transfer object for a single menu item with completeness guard.
class MenuScannerItemDto {
  final String originalName;
  final String translatedName;
  final String? description;
  final double price;
  final bool hasPriceField;

  const MenuScannerItemDto({
    required this.originalName,
    required this.translatedName,
    this.description,
    required this.price,
    this.hasPriceField = true,
  });

  /// 判定品項是否已完全生成完畢（最小原子單元）
  /// 只有原文非空、譯名非空、且作為結尾欄位的 price 已經生成的品項，才允許進入畫面渲染，
  /// 確保每個項目都是 100% 完整產出，避免出現殘缺空白或尚未翻譯完成的中繼卡片。
  bool get isComplete =>
      originalName.trim().isNotEmpty &&
      translatedName.trim().isNotEmpty &&
      hasPriceField;

  factory MenuScannerItemDto.fromDynamic(dynamic raw) {
    if (raw is! Map) {
      return const MenuScannerItemDto(
        originalName: '',
        translatedName: '',
        price: 0.0,
        hasPriceField: false,
      );
    }

    final originalName = raw['originalName']?.toString().trim() ?? '';
    final translatedName = raw['translatedName']?.toString().trim() ?? '';
    final rawDesc = raw['description']?.toString().trim();
    final description = (rawDesc != null && rawDesc.isNotEmpty) ? rawDesc : null;

    final hasPriceField = raw.containsKey('price');
    double price = 0.0;
    final rawPrice = raw['price'];
    if (rawPrice is num) {
      price = rawPrice.toDouble();
    } else if (rawPrice is String) {
      price = double.tryParse(rawPrice.replaceAll(RegExp(r'[^\d.]'), '')) ?? 0.0;
    }

    return MenuScannerItemDto(
      originalName: originalName,
      translatedName: translatedName,
      description: description,
      price: price,
      hasPriceField: hasPriceField,
    );
  }

  MenuScannerItem toDomain() {
    return MenuScannerItem(
      originalName: originalName,
      translatedName: translatedName,
      description: description,
      price: price,
    );
  }
}

/// Robust, type-safe payload parser for Menu Scanner responses.
/// 
/// Handles dual-schema payloads (nested under `data` or flat in root),
/// protects against streaming deserialization type errors (e.g. string as list),
/// and filters incomplete trailing items during streaming hydration.
class MenuScannerPayloadParser {
  /// Resolves the actual data node from either a nested `{status, data: {...}}` 
  /// response or a flat `{storeName, items: [...]}` response.
  static Map<dynamic, dynamic> _resolveDataNode(Map<dynamic, dynamic> jsonMap) {
    final data = jsonMap['data'];
    if (data is Map) {
      return data;
    }
    return jsonMap;
  }

  /// Parses an intermediate streaming snapshot.
  /// 
  /// - Resilient to string/null repairs on partial lists (never throws TypeError).
  /// - Only yields complete items (`isComplete == true`), holding back trailing partial items
  ///   until their attributes are fully generated by the LLM.
  static MenuScannerRecord parseStreamingSnapshot(Map<String, dynamic> jsonMap) {
    try {
      final dataNode = _resolveDataNode(jsonMap);
      
      final storeName = dataNode['storeName']?.toString().trim() ?? '';

      final rawItems = dataNode['items'];
      final List<MenuScannerItem> completeItems = [];

      if (rawItems is List) {
        for (final raw in rawItems) {
          final dto = MenuScannerItemDto.fromDynamic(raw);
          if (dto.isComplete) {
            completeItems.add(dto.toDomain());
          }
        }
      }

      return MenuScannerRecord(
        id: '',
        timestamp: DateTime.now(),
        storeName: storeName,
        items: completeItems,
        imagePaths: const [],
        translatedImagePaths: const {},
      );
    } catch (_) {
      return MenuScannerRecord.empty();
    }
  }

  /// Parses the final complete response for standard non-streaming or stream-finished execution.
  static MenuScannerRecord parseFinalResponse(Map<String, dynamic> jsonMap) {
    final status = jsonMap['status']?.toString();
    final message = jsonMap['message']?.toString();

    if (status != null && status != 'success') {
      throw Exception(message ?? '菜單辨識解析失敗，請重新拍攝清晰的照片。');
    }

    final dataNode = _resolveDataNode(jsonMap);
    final storeName = dataNode['storeName']?.toString().trim();
    final finalStoreName = (storeName != null && storeName.isNotEmpty) ? storeName : '未知餐廳菜單';

    final rawItems = dataNode['items'];
    final List<MenuScannerItem> items = [];

    if (rawItems is List) {
      for (final raw in rawItems) {
        final dto = MenuScannerItemDto.fromDynamic(raw);
        // In final response, include items that have at least an original or translated name
        if (dto.originalName.isNotEmpty || dto.translatedName.isNotEmpty) {
          items.add(dto.toDomain());
        }
      }
    }

    return MenuScannerRecord(
      id: '',
      timestamp: DateTime.now(),
      storeName: finalStoreName,
      items: items,
      imagePaths: const [],
      translatedImagePaths: const {},
    );
  }
}
