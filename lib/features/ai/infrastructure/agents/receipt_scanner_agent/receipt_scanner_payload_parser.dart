import 'package:lens_wise/features/receipt_scanner/domain/models/receipt_scanner_record.dart';

/// Data transfer object for a single receipt item with completeness guard.
class ReceiptItemDto {
  final String originalName;
  final String translatedName;
  final double price;
  final bool hasPriceField;

  const ReceiptItemDto({
    required this.originalName,
    required this.translatedName,
    required this.price,
    this.hasPriceField = true,
  });

  /// 判定品項是否已完全生成完畢（最小原子單元）
  /// 只有原文非空、譯名非空、且作為結尾欄位的 price 已經生成的品項，才允許進入畫面渲染，
  /// 確保每個項目都是 100% 完整產出，避免出現殘缺空白或尚未翻譯完成的中繼卡片。
  bool get isComplete =>
      originalName.trim().isNotEmpty &&
      translatedName.trim().isNotEmpty &&
      hasPriceField;

  factory ReceiptItemDto.fromDynamic(dynamic raw) {
    if (raw is! Map) {
      return const ReceiptItemDto(
        originalName: '',
        translatedName: '',
        price: 0.0,
        hasPriceField: false,
      );
    }

    final originalName = raw['originalName']?.toString().trim() ?? '';
    final translatedName = raw['translatedName']?.toString().trim() ?? '';

    final hasPriceField = raw.containsKey('price');
    double price = 0.0;
    final rawPrice = raw['price'];
    if (rawPrice is num) {
      price = rawPrice.toDouble();
    } else if (rawPrice is String) {
      price = double.tryParse(rawPrice.replaceAll(RegExp(r'[^\d.]'), '')) ?? 0.0;
    }

    return ReceiptItemDto(
      originalName: originalName,
      translatedName: translatedName,
      price: price,
      hasPriceField: hasPriceField,
    );
  }

  ReceiptItem toDomain() {
    return ReceiptItem(
      originalName: originalName,
      translatedName: translatedName,
      price: price,
    );
  }
}

/// Data transfer object for a receipt fee (discount or tax) with completeness guard.
class ReceiptFeeItemDto {
  final String name;
  final double amount;
  final bool hasAmountField;

  const ReceiptFeeItemDto({
    required this.name,
    required this.amount,
    this.hasAmountField = true,
  });

  bool get isComplete => name.trim().isNotEmpty && hasAmountField;

  factory ReceiptFeeItemDto.fromDynamic(dynamic raw) {
    if (raw is! Map) {
      return const ReceiptFeeItemDto(name: '', amount: 0.0, hasAmountField: false);
    }

    final name = raw['name']?.toString().trim() ?? '';
    final hasAmountField = raw.containsKey('amount');
    double amount = 0.0;
    final rawAmount = raw['amount'];
    if (rawAmount is num) {
      amount = rawAmount.toDouble();
    } else if (rawAmount is String) {
      final isNegative = rawAmount.trim().startsWith('-');
      final parsed = double.tryParse(rawAmount.replaceAll(RegExp(r'[^\d.]'), '')) ?? 0.0;
      amount = isNegative ? -parsed : parsed;
    }

    return ReceiptFeeItemDto(
      name: name,
      amount: amount,
      hasAmountField: hasAmountField,
    );
  }

  ReceiptFeeItem toDomain() {
    return ReceiptFeeItem(name: name, amount: amount);
  }
}

/// Robust, type-safe payload parser for Receipt Scanner responses.
/// 
/// Handles dual-schema payloads (nested under `data` or flat in root),
/// protects against streaming deserialization type errors (e.g. string as list),
/// and filters incomplete trailing items during streaming hydration.
class ReceiptScannerPayloadParser {
  /// Resolves the actual data node from either a nested `{status, data: {...}}` 
  /// response or a flat `{storeName, items: [...]}` response.
  static Map<dynamic, dynamic> _resolveDataNode(Map<dynamic, dynamic> jsonMap) {
    final data = jsonMap['data'];
    if (data is Map) {
      return data;
    }
    return jsonMap;
  }

  static double _parseDouble(dynamic value) {
    if (value == null) return 0.0;
    if (value is num) return value.toDouble();
    if (value is String) {
      final isNegative = value.trim().startsWith('-');
      final parsed = double.tryParse(value.replaceAll(RegExp(r'[^\d.]'), '')) ?? 0.0;
      return isNegative ? -parsed : parsed;
    }
    return 0.0;
  }

  /// Parses an intermediate streaming snapshot.
  /// 
  /// - Resilient to string/null repairs on partial lists (never throws TypeError).
  /// - Only yields complete items (`isComplete == true`), holding back trailing partial items
  ///   until their attributes are fully generated by the LLM.
  static ReceiptScannerRecord parseStreamingSnapshot(Map<String, dynamic> jsonMap) {
    try {
      final dataNode = _resolveDataNode(jsonMap);

      final storeName = dataNode['storeName']?.toString().trim() ?? '';
      final receiptDate = (dataNode['receiptDateTime'] ?? dataNode['receiptDate'])?.toString().trim();
      final currency = dataNode['currency']?.toString().trim();

      // Items
      final rawItems = dataNode['items'];
      final List<ReceiptItem> completeItems = [];
      if (rawItems is List) {
        for (final raw in rawItems) {
          final dto = ReceiptItemDto.fromDynamic(raw);
          if (dto.isComplete) {
            completeItems.add(dto.toDomain());
          }
        }
      }

      // Discounts
      final rawDiscounts = dataNode['discounts'];
      final List<ReceiptFeeItem> completeDiscounts = [];
      if (rawDiscounts is List) {
        for (final raw in rawDiscounts) {
          final dto = ReceiptFeeItemDto.fromDynamic(raw);
          if (dto.isComplete) {
            completeDiscounts.add(dto.toDomain());
          }
        }
      }

      // Taxes
      final rawTaxes = dataNode['taxes'];
      final List<ReceiptFeeItem> completeTaxes = [];
      if (rawTaxes is List) {
        for (final raw in rawTaxes) {
          final dto = ReceiptFeeItemDto.fromDynamic(raw);
          if (dto.isComplete) {
            completeTaxes.add(dto.toDomain());
          }
        }
      }

      // Subtotal & Total
      final itemsTotal = completeItems.fold<double>(0.0, (acc, item) => acc + item.price);
      final discountsTotal = completeDiscounts.fold<double>(0.0, (acc, fee) => acc + fee.amount);
      final taxesTotal = completeTaxes.fold<double>(0.0, (acc, fee) => acc + fee.amount);

      final subtotal = dataNode.containsKey('subtotal')
          ? _parseDouble(dataNode['subtotal'])
          : itemsTotal;

      final totalAmount = dataNode.containsKey('totalAmount')
          ? _parseDouble(dataNode['totalAmount'])
          : (subtotal + taxesTotal + discountsTotal);

      return ReceiptScannerRecord(
        id: '',
        timestamp: DateTime.now(),
        receiptDate: (receiptDate != null && receiptDate.isNotEmpty) ? receiptDate : null,
        storeName: storeName,
        currency: (currency != null && currency.isNotEmpty) ? currency : null,
        subtotal: subtotal,
        items: completeItems,
        discounts: completeDiscounts,
        taxes: completeTaxes,
        totalAmount: totalAmount,
        imagePaths: const [],
      );
    } catch (_) {
      return ReceiptScannerRecord.empty();
    }
  }
}
