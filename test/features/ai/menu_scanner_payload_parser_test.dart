import 'package:flutter_test/flutter_test.dart';
import 'package:lens_wise/features/ai/infrastructure/agents/menu_scanner_agent/menu_scanner_payload_parser.dart';

void main() {
  group('MenuScannerPayloadParser', () {
    test('parses standard nested JSON correctly', () {
      final jsonMap = {
        'status': 'success',
        'data': {
          'storeName': '一蘭拉麵',
          'items': [
            {
              'originalName': '天然豚骨ラーメン',
              'translatedName': '天然豚骨拉麵',
              'description': '招牌豚骨湯頭',
              'price': 298.0,
            },
          ],
        },
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      expect(record.storeName, '一蘭拉麵');
      expect(record.items.length, 1);
      expect(record.items.first.originalName, '天然豚骨ラーメン');
      expect(record.items.first.translatedName, '天然豚骨拉麵');
      expect(record.items.first.price, 298.0);
    });

    test('parses flat JSON correctly when data wrapper is omitted', () {
      final jsonMap = {
        'storeName': '一蘭拉麵 (Flat)',
        'items': [
          {
            'originalName': '替玉',
            'translatedName': '加麵',
            'price': 58,
          },
        ],
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      expect(record.storeName, '一蘭拉麵 (Flat)');
      expect(record.items.length, 1);
      expect(record.items.first.originalName, '替玉');
      expect(record.items.first.translatedName, '加麵');
      expect(record.items.first.price, 58.0);
    });

    test('handles string items safely without throwing TypeError (癥結 1)', () {
      // repairJson during "items": transition repairs items to "" or null
      final jsonMap = {
        'status': 'success',
        'data': {
          'storeName': '拉麵店',
          'items': '', // String, not List!
        },
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      expect(record.storeName, '拉麵店');
      expect(record.items, isEmpty);
    });

    test('filters out incomplete trailing item during streaming', () {
      final jsonMap = {
        'status': 'success',
        'data': {
          'storeName': '拉麵店',
          'items': [
            // Item 1: Complete
            {
              'originalName': '拉麵',
              'translatedName': '豚骨拉麵',
              'price': 100.0,
            },
            // Item 2: Incomplete trailing item being streamed (no translatedName yet)
            {
              'originalName': '半替玉',
              'translatedName': '',
              'price': 0.0,
            },
          ],
        },
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      // Only complete items should be yielded to UI!
      expect(record.items.length, 1);
      expect(record.items.first.originalName, '拉麵');

      // Now LLM finishes Item 2
      final updatedJsonMap = {
        'status': 'success',
        'data': {
          'storeName': '拉麵店',
          'items': [
            {
              'originalName': '拉麵',
              'translatedName': '豚骨拉麵',
              'price': 100.0,
            },
            {
              'originalName': '半替玉',
              'translatedName': '半份加麵',
              'price': 50.0,
            },
          ],
        },
      };

      final updatedRecord = MenuScannerPayloadParser.parseStreamingSnapshot(updatedJsonMap);
      expect(updatedRecord.items.length, 2);
      expect(updatedRecord.items[1].originalName, '半替玉');
      expect(updatedRecord.items[1].translatedName, '半份加麵');
      expect(updatedRecord.items[1].price, 50.0);
    });

    test('item is not complete if price field has not yet been emitted', () {
      final jsonMap = {
        'status': 'success',
        'data': {
          'storeName': '拉麵店',
          'items': [
            {
              'originalName': '拉麵',
              'translatedName': '豚骨拉麵',
              // price field is omitted (still being generated by LLM)
            },
          ],
        },
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      expect(record.items, isEmpty);
    });

    test('handles dynamic map types safely', () {
      final dynamicList = <dynamic>[
        <dynamic, dynamic>{
          'originalName': '煎餃',
          'translatedName': '日式煎餃',
          'price': '80', // String price safely parsed to double
        }
      ];

      final jsonMap = {
        'data': {
          'storeName': '日式餐廳',
          'items': dynamicList,
        }
      };

      final record = MenuScannerPayloadParser.parseStreamingSnapshot(jsonMap);
      expect(record.items.length, 1);
      expect(record.items.first.originalName, '煎餃');
      expect(record.items.first.translatedName, '日式煎餃');
      expect(record.items.first.price, 80.0);
    });

    test('parseFinalResponse throws on error status', () {
      final jsonMap = {
        'status': 'needs_more_info',
        'message': '圖片模糊無法識別',
      };

      expect(
        () => MenuScannerPayloadParser.parseFinalResponse(jsonMap),
        throwsA(isA<Exception>()),
      );
    });
  });
}
